-- Oracle DB에서 직접 실행 (ddl-auto: none 설정으로 자동 생성되지 않음)

CREATE TABLE MEMBERS (
    USER_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NAME      VARCHAR2(100)  NOT NULL,
    BIRTHDATE DATE           NOT NULL,
    EMAIL     VARCHAR2(255)  NOT NULL,
    PASSWORD  VARCHAR2(255)  NOT NULL,
    USER_ROLE VARCHAR2(20)   DEFAULT 'USER' NOT NULL,
    IS_DELETED NUMBER(1)     DEFAULT 0 NOT NULL,
    CONSTRAINT PK_MEMBERS PRIMARY KEY (USER_ID),
    CONSTRAINT UQ_MEMBERS_EMAIL UNIQUE (EMAIL)
);

-- 기존 테이블에서 변경할 경우 아래 DDL 사용

CREATE SEQUENCE SEQ_DAILY_TODO
    START WITH 1
    INCREMENT BY 1
    NOCACHE;

CREATE TABLE DAILY_TODO (
    DAILY_TODO_ID NUMBER(19)    NOT NULL,
    USER_ID     NUMBER(19)    NOT NULL,
    CONTENT       VARCHAR2(500) NOT NULL,
    IS_DONE       CHAR(1)       DEFAULT 'N' NOT NULL,
    TODO_DATE     DATE          NOT NULL,
    CREATED_AT    TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT    TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_DAILY_TODO PRIMARY KEY (DAILY_TODO_ID),
    CONSTRAINT FK_DAILY_TODO_MEMBERS FOREIGN KEY (USER_ID)
        REFERENCES MEMBERS (USER_ID),
    CONSTRAINT CK_DAILY_TODO_IS_DONE CHECK (IS_DONE IN ('Y', 'N'))
);

CREATE INDEX IDX_DAILY_TODO_USER_ID ON DAILY_TODO (USER_ID, TODO_DATE);
